import { Schema, type Types } from 'mongoose';
import { type DataScopeType, type UserType } from '../../../common/request-context/request-actor';

export const USER_MODEL = 'User';

export const USER_TYPES = [
  'STAFF',
  'OPERATOR_STAFF',
  'DRIVER',
  'PARTNER_USER',
  'CUSTOMER',
] as const satisfies readonly UserType[];

export const USER_STATUSES = ['ACTIVE', 'INVITED', 'SUSPENDED', 'DEACTIVATED'] as const;
export type UserStatus = (typeof USER_STATUSES)[number];

export const DATA_SCOPE_TYPES = [
  'ALL',
  'OWN_OPERATOR',
  'SELECTED_OPERATORS',
  'OWN_PARTNER',
  'OWN_RECORDS',
  'ASSIGNED_RECORDS',
] as const satisfies readonly DataScopeType[];

export interface UserMfa {
  enabled: boolean;
  /** TOTP secret, encrypted with FieldEncryptionService. Never leaves the backend. */
  secretEncrypted?: string | null;
  /** Secret generated by enrolment and not yet confirmed with a code. */
  pendingSecretEncrypted?: string | null;
  /** SHA-256 of each unused recovery code. */
  recoveryCodeHashes: string[];
  /** Last accepted TOTP time step; a code for the same or an earlier step is a replay. */
  lastUsedTimeStep?: number | null;
  enabledAt?: Date | null;
}

export interface User {
  firebaseUid?: string;
  googleFirebaseUid?: string;
  appleFirebaseUid?: string;
  authProvider?: string;
  name?: string;
  /** Lower-cased. */
  email?: string;
  /** E.164. */
  phone?: string;
  emailVerifiedAt?: Date | null;
  phoneVerifiedAt?: Date | null;
  /** Argon2id PHC string. Absent for accounts that only use OTP. */
  passwordHash?: string | null;
  passwordChangedAt?: Date | null;
  userType: UserType;
  roleIds: Types.ObjectId[];
  operatorId?: Types.ObjectId;
  partnerId?: Types.ObjectId;
  dataScope: { type: DataScopeType; operatorIds: Types.ObjectId[] };
  status: UserStatus;
  /** Incremented on any role, override, scope or status change (authorization.md §6). */
  permissionVersion: number;
  mfa: UserMfa;
  preferredLanguage: string;
  lastLoginAt?: Date | null;
  createdAt?: Date;
  updatedAt?: Date;
}

/** `users` (database-architecture.md §1). */
export const userSchema = new Schema<User>(
  {
    firebaseUid: { type: String, maxlength: 128 },
    googleFirebaseUid: { type: String, maxlength: 128 },
    appleFirebaseUid: { type: String, maxlength: 128 },
    authProvider: { type: String, enum: ['google', 'apple', 'whatsapp'] },
    name: { type: String, trim: true, maxlength: 120 },
    email: { type: String, lowercase: true, trim: true, maxlength: 254 },
    phone: { type: String, maxlength: 16 },
    emailVerifiedAt: { type: Date, default: null },
    phoneVerifiedAt: { type: Date, default: null },
    passwordHash: { type: String, default: null },
    passwordChangedAt: { type: Date, default: null },
    userType: { type: String, enum: USER_TYPES, required: true },
    roleIds: { type: [Schema.Types.ObjectId], default: [] },
    operatorId: { type: Schema.Types.ObjectId },
    partnerId: { type: Schema.Types.ObjectId },
    dataScope: {
      type: { type: String, enum: DATA_SCOPE_TYPES, required: true },
      operatorIds: { type: [Schema.Types.ObjectId], default: [] },
    },
    status: { type: String, enum: USER_STATUSES, required: true, default: 'ACTIVE' },
    permissionVersion: { type: Number, required: true, default: 1, min: 1 },
    mfa: {
      enabled: { type: Boolean, required: true, default: false },
      secretEncrypted: { type: String, default: null },
      pendingSecretEncrypted: { type: String, default: null },
      recoveryCodeHashes: { type: [String], default: [] },
      lastUsedTimeStep: { type: Number, default: null },
      enabledAt: { type: Date, default: null },
    },
    preferredLanguage: { type: String, required: true, default: 'en', maxlength: 8 },
    lastLoginAt: { type: Date, default: null },
  },
  { collection: 'users', timestamps: true, versionKey: false },
);

// Unique only where the field is set: many customers have no email, many staff have no phone
userSchema.index(
  { email: 1 },
  { unique: true, partialFilterExpression: { email: { $type: 'string' } } },
);
userSchema.index(
  { phone: 1 },
  { unique: true, partialFilterExpression: { phone: { $type: 'string' } } },
);
userSchema.index({ operatorId: 1, status: 1 });

userSchema.index(
  { firebaseUid: 1 },
  { unique: true, partialFilterExpression: { firebaseUid: { $type: 'string' } } },
);

for (const field of ['googleFirebaseUid', 'appleFirebaseUid'] as const) {
  userSchema.index(
    { [field]: 1 },
    { unique: true, partialFilterExpression: { [field]: { $type: 'string' } } },
  );
}
